// Builds the JavaScriptCore + OpenGL ES Apple TV app (client-tvos/jsc/) and runs it on a paired
// Apple TV or a tvOS simulator. See client-tvos/jsc/README.md.
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CANVAS_OPS, GL_OPS, OP } from '../client-tvos/jsc/runtime/ops.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const appDir = path.join(root, 'client-tvos/jsc');
const www = path.join(appDir, 'www');
const TEAM_ID = process.env.TVOS_TEAM_ID || 'PX72AL9366';
const BUNDLE_ID = process.env.TVOS_BUNDLE_ID || 'com.isaacthoman.aerodance.tv.jsc';

const USAGE = `Usage: node scripts/tvos-jsc.ts <command> [options]

  build [--sim] [--game]           bundle the runtime, the Aero benchmark (and with --game the
                                   game) into client-tvos/jsc/www/, then build the app for the
                                   Apple TV (or the simulator)
  run [--sim <udid>] [--device <udid>] --config <json>
                                   install the built app and launch it with a launch config
                                   (see client-tvos/jsc/README.md), printing its console

Signing uses TVOS_TEAM_ID (default ${TEAM_ID}) and TVOS_BUNDLE_ID (default ${BUNDLE_ID}).`;

function run(command: string, args: string[], cwd = root, env: NodeJS.ProcessEnv = process.env) {
  const result = spawnSync(command, args, { cwd, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw Error(`${command} ${args.slice(0, 3).join(' ')} failed (exit ${result.status})`);
}

/** src/generated/ops.h: the opcodes as C constants, and their names for GL error messages. */
function writeOpsHeader() {
  const dir = path.join(appDir, 'src/generated');
  mkdirSync(dir, { recursive: true });
  const lines = Object.entries(OP).map(([name, n]) => `#define OP_${name} ${n}`);
  const names = GL_OPS.map((name) => `"${name}"`).join(', ');
  writeFileSync(path.join(dir, 'ops.h'), `// Generated by scripts/tvos-jsc.ts from client-tvos/jsc/runtime/ops.ts.\n#pragma once\n${lines.join('\n')}\nstatic const char *const kOpNames[] = { ${names} };\n// ${CANVAS_OPS.length} canvas ops from 200.\n`);
}

// Fonts the canvas UI uses: Inter as the web build loads it from Google Fonts (weights 200 and
// 800), and Nunito from @fontsource. Bundled as <Family>__<weight>.<ext> (src/Fonts.mm).
const INTER = {
  200: 'https://fonts.gstatic.com/s/inter/v20/UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuDyfMZg.ttf',
  800: 'https://fonts.gstatic.com/s/inter/v20/UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuDyYMZg.ttf',
};
async function copyFonts() {
  const out = path.join(www, 'fonts');
  mkdirSync(out, { recursive: true });
  const cache = path.join(root, '.cache/fonts');
  mkdirSync(cache, { recursive: true });
  for (const [weight, url] of Object.entries(INTER)) {
    const file = path.join(cache, `Inter__${weight}.ttf`);
    if (!existsSync(file)) {
      const res = await fetch(url);
      if (!res.ok) throw Error(`Inter ${weight}: ${res.status}`);
      writeFileSync(file, Buffer.from(await res.arrayBuffer()));
    }
    cpSync(file, path.join(out, `Inter__${weight}.ttf`));
  }
  for (const weight of [700, 900]) {
    cpSync(path.join(root, `node_modules/@fontsource/nunito/files/nunito-latin-${weight}-normal.woff`), path.join(out, `Nunito__${weight}.woff`));
  }
}

async function build(sim: boolean, game: boolean) {
  writeOpsHeader();
  rmSync(www, { recursive: true, force: true });
  mkdirSync(www, { recursive: true });
  run('npx', ['rolldown', './client-tvos/jsc/runtime/index.ts', '--format', 'iife', '--minify', '--file', 'client-tvos/jsc/www/runtime.js']);
  run('node', ['scripts/tvos.ts', 'bench']);
  cpSync(path.join(root, 'client-tvos/bench/dist'), path.join(www, 'bench'), { recursive: true });
  run('npx', ['rolldown', './client-tvos/jsc/bench/bridgeBench.ts', '--format', 'iife', '--minify', '--file', 'client-tvos/jsc/www/bench/bridge.js']);
  run('npx', ['rolldown', './client-tvos/jsc/bench/canvasTest.ts', '--format', 'iife', '--minify', '--file', 'client-tvos/jsc/www/bench/canvas-test.js']);
  if (game) {
    run('npx', ['vite', 'build', '--config', 'client-tvos/jsc/vite.config.ts']);
    cpSync(path.join(appDir, 'dist'), path.join(www), { recursive: true });
  }
  await copyFonts();
  writeFileSync(path.join(www, 'config.json'), JSON.stringify(game
    ? { script: 'game.js', url: 'http://aerodance.local/?input=ghost', fit: 'fill', pixelated: true }
    : { script: 'bench/aero-bench.js', url: 'http://aerodance.local/bench/aero-bench.html', fit: 'contain' }));
  if (spawnSync('xcodegen', ['--version']).error) throw Error('XcodeGen is needed to generate the Xcode project: brew install xcodegen');
  const env = { ...process.env, TVOS_TEAM_ID: TEAM_ID, TVOS_BUNDLE_ID: BUNDLE_ID };
  run('xcodegen', ['generate', '--quiet'], appDir, env);
  run('xcodebuild', [
    '-project', 'AerodanceJSC.xcodeproj', '-scheme', 'AerodanceJSC', '-configuration', 'Release',
    '-destination', sim ? 'generic/platform=tvOS Simulator' : 'generic/platform=tvOS', '-derivedDataPath', 'build',
    ...(sim ? ['CODE_SIGNING_ALLOWED=NO', 'ARCHS=arm64'] : ['-allowProvisioningUpdates', '-allowProvisioningDeviceRegistration']), '-quiet', 'build',
  ], appDir, env);
  console.log(`Built ${appPath(sim)}`);
}

const appPath = (sim: boolean) => path.join(appDir, `build/Build/Products/Release-${sim ? 'appletvsimulator' : 'appletvos'}/aerodance.app`);

function launch(target: { sim?: string; device?: string }, config: string) {
  if (target.sim) {
    run('xcrun', ['simctl', 'install', target.sim, appPath(true)]);
    run('xcrun', ['simctl', 'launch', '--console-pty', '--terminate-running-process', target.sim, BUNDLE_ID, '--config', config]);
  } else {
    const device = target.device ?? '';
    run('xcrun', ['devicectl', 'device', 'install', 'app', '--device', device, '--quiet', appPath(false)]);
    run('xcrun', ['devicectl', 'device', 'process', 'launch', '--device', device, '--terminate-existing', '--console', BUNDLE_ID, '--config', config]);
  }
}

async function main() {
  const [cmd, ...args] = process.argv.slice(2);
  const flag = (name: string) => { const i = args.indexOf(name); return i < 0 ? undefined : args.splice(i, 2)[1] ?? ''; };
  const has = (name: string) => { const i = args.indexOf(name); if (i >= 0) args.splice(i, 1); return i >= 0; };
  if (!cmd || cmd === 'help' || cmd === '--help') return console.log(USAGE);
  if (cmd === 'build') return build(has('--sim'), has('--game'));
  if (cmd === 'run') {
    const sim = flag('--sim'), device = flag('--device'), config = flag('--config') ?? readFileSync(path.join(www, 'config.json'), 'utf8');
    if (!sim && !device) throw Error('run needs --sim <udid> or --device <udid>');
    return launch({ sim, device }, config);
  }
  throw Error(`Unknown command ${cmd}\n\n${USAGE}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
