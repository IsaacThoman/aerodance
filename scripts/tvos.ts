// Builds the JavaScriptCore + OpenGL ES Apple TV app (apps/tvos/) and runs it on a paired
// Apple TV or a tvOS simulator. See apps/tvos/README.md.
import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { CANVAS_OPS, GL_OPS, OP } from '../apps/tvos/runtime/ops.ts';
import { checkSite, copyInter, DEFAULT_BUNDLE_ID, DEFAULT_TEAM_ID, root, SITE } from './apple.ts';

const appDir = path.join(root, 'apps/tvos');
const www = path.join(appDir, 'www');
const TEAM_ID = process.env.TVOS_TEAM_ID || DEFAULT_TEAM_ID;
const BUNDLE_ID = process.env.TVOS_BUNDLE_ID || DEFAULT_BUNDLE_ID;

const USAGE = `Usage: node scripts/tvos.ts <command> [options]

  build [--sim] [--game] [--release] [--site <origin>] [--ghost]
                                   bundle the runtime, the Aero benchmark (and with --game the
                                   game) into apps/tvos/www/, then build the app for the
                                   Apple TV (or the simulator). --release leaves out the local
                                   network permissions that development reports use. --site is
                                   the deployed game the app pairs phones through (default
                                   ${SITE}; a PR preview is https://<number>.aerodance.party).
                                   The game plays from a paired phone's camera; --ghost opens it
                                   with the autoplay ghost instead
  run [--sim <udid>] [--device <udid>] --config <json>
                                   install the built app and launch it with a launch config
                                   (see apps/tvos/README.md), printing its console

Signing uses TVOS_TEAM_ID (default ${TEAM_ID}) and TVOS_BUNDLE_ID (default ${BUNDLE_ID}).`;

function run(command: string, args: string[], cwd = root, env: NodeJS.ProcessEnv = process.env) {
  const result = spawnSync(command, args, { cwd, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw Error(`${command} ${args.slice(0, 3).join(' ')} failed (exit ${result.status})`);
}

/** src/generated/ops.h: the opcodes as C constants, and their names for GL error messages. */
function writeOpsHeader() {
  const dir = path.join(appDir, 'src/generated');
  mkdirSync(dir, { recursive: true });
  const lines = Object.entries(OP).map(([name, n]) => `#define OP_${name} ${n}`);
  const names = GL_OPS.map((name) => `"${name}"`).join(', ');
  writeFileSync(path.join(dir, 'ops.h'), `// Generated by scripts/tvos.ts from apps/tvos/runtime/ops.ts.\n#pragma once\n${lines.join('\n')}\nstatic const char *const kOpNames[] = { ${names} };\n// ${CANVAS_OPS.length} canvas ops from 200.\n`);
}

// The home-screen icon and Top Shelf banners, as brand assets in src/generated/.
// The layered (parallax) icon comes from assets/tv-icon (render.ts --tv-icons).
const ICON = 'falls-sky-soft-glass';
// The brand assets name project.yml gives as the app icon.
const ICON_SET = 'App Icon & Top Shelf Image';
const ICON_STACKS = [
  { name: 'App Icon - App Store', size: '1280x768', scales: { '1x': '1280x768' } },
  { name: 'App Icon', size: '400x240', scales: { '1x': '400x240', '2x': '800x480' } },
];
const TOP_SHELF = 'meadow-duet';
const TOP_SHELF_SETS = [
  { name: 'Top Shelf Image', variant: 'standard', role: 'top-shelf-image', size: '1920x720' },
  { name: 'Top Shelf Image Wide', variant: 'wide', role: 'top-shelf-image-wide', size: '2320x720' },
];

/** src/generated/Assets.xcassets: the App Store and home-screen icons, plus Top Shelf banners. */
function writeBrandAssets() {
  const source = path.join(root, 'assets/tv-icon', ICON);
  const catalog = path.join(appDir, 'src/generated/Assets.xcassets');
  rmSync(catalog, { recursive: true, force: true });
  const contents = (dir: string, json: object = {}) => {
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, 'Contents.json'), JSON.stringify({ ...json, info: { author: 'xcode', version: 1 } }, null, 2));
  };
  // assets/tv-icon numbers the layers back to front (1-sky.png, ...); a stack lists them front to back.
  const layers = readdirSync(path.join(source, ICON_STACKS[0].size)).filter((f) => f.endsWith('.png')).sort().reverse().map((f) => path.basename(f, '.png'));
  if (!layers.length) throw Error(`No icon layers in ${source}`);
  contents(catalog);
  const brand = path.join(catalog, `${ICON_SET}.brandassets`);
  for (const stack of ICON_STACKS) {
    const dir = path.join(brand, `${stack.name}.imagestack`);
    contents(dir, { layers: layers.map((layer) => ({ filename: `${layer}.imagestacklayer` })) });
    for (const layer of layers) {
      contents(path.join(dir, `${layer}.imagestacklayer`));
      const set = path.join(dir, `${layer}.imagestacklayer/Content.imageset`);
      mkdirSync(set, { recursive: true });
      const images = Object.entries(stack.scales).map(([scale, size]) => {
        const filename = `${layer}@${scale}.png`;
        cpSync(path.join(source, size, `${layer}.png`), path.join(set, filename));
        return { idiom: 'tv', filename, scale };
      });
      contents(set, { images });
    }
  }
  for (const shelf of TOP_SHELF_SETS) {
    const set = path.join(brand, `${shelf.name}.imageset`);
    mkdirSync(set, { recursive: true });
    const images = ['1x', '2x'].map((scale) => {
      const filename = `${TOP_SHELF}${scale === '2x' ? '@2x' : ''}.png`;
      cpSync(path.join(root, 'assets/top-shelf', shelf.variant, filename), path.join(set, filename));
      return { idiom: 'tv', filename, scale };
    });
    contents(set, { images });
  }
  contents(brand, { assets: [
    ...ICON_STACKS.map((stack) => ({ filename: `${stack.name}.imagestack`, idiom: 'tv', role: 'primary-app-icon', size: stack.size })),
    ...TOP_SHELF_SETS.map((shelf) => ({ filename: `${shelf.name}.imageset`, idiom: 'tv', role: shelf.role, size: shelf.size })),
  ] });
}

// The launch screen: SPLASH from assets/, shown at its natural size, so scaled to fill the
// 1920x1080-point screen at 1x (1080p) and 2x (4K). The image set project.yml's UILaunchScreen names,
// which main.mm keeps up until the game has loaded.
const SPLASH = 'splash1-logo.png';
const SPLASH_SET = 'Launch Image';

/** The launch image set in src/generated/Assets.xcassets (after writeBrandAssets clears the catalog). */
function writeSplash() {
  const set = path.join(appDir, 'src/generated/Assets.xcassets', `${SPLASH_SET}.imageset`);
  mkdirSync(set, { recursive: true });
  const images = [{ scale: '1x', width: 1920, height: 1080 }, { scale: '2x', width: 3840, height: 2160 }].map(({ scale, width, height }) => {
    const filename = `splash@${scale}.png`;
    run('sips', ['--resampleHeightWidth', String(height), String(width), path.join(root, 'assets', SPLASH), '--out', path.join(set, filename)], root);
    return { idiom: 'tv', filename, scale };
  });
  writeFileSync(path.join(set, 'Contents.json'), JSON.stringify({ images, info: { author: 'xcode', version: 1 } }, null, 2));
}

// Fonts the canvas UI uses: Inter (scripts/apple.ts) and Nunito from @fontsource. Bundled as
// <Family>__<weight>.<ext> (src/Fonts.mm).
async function copyFonts() {
  const out = path.join(www, 'fonts');
  await copyInter(out);
  for (const weight of [700, 900]) {
    cpSync(path.join(root, `node_modules/@fontsource/nunito/files/nunito-latin-${weight}-normal.woff`), path.join(out, `Nunito__${weight}.woff`));
  }
}

/** The Aero world benchmark (apps/tvos/bench/) into apps/tvos/bench/dist/. */
function buildBench() {
  const out = path.join(root, 'apps/tvos/bench/dist');
  rmSync(out, { recursive: true, force: true });
  run('npx', ['rolldown', './apps/tvos/bench/aeroBench.ts', '--format', 'iife', '--minify', '--file', 'apps/tvos/bench/dist/aero-bench.js']);
  cpSync(path.join(root, 'apps/tvos/bench/aero-bench.html'), path.join(out, 'aero-bench.html'));
}

async function build(sim: boolean, game: boolean, release: boolean, site = SITE, ghost = false) {
  checkSite(site);
  writeOpsHeader();
  writeBrandAssets();
  writeSplash();
  rmSync(www, { recursive: true, force: true });
  mkdirSync(www, { recursive: true });
  run('npx', ['rolldown', './apps/tvos/runtime/index.ts', '--format', 'iife', '--minify', '--file', 'apps/tvos/www/runtime.js']);
  buildBench();
  cpSync(path.join(root, 'apps/tvos/bench/dist'), path.join(www, 'bench'), { recursive: true });
  run('npx', ['rolldown', './apps/tvos/bench/bridgeBench.ts', '--format', 'iife', '--minify', '--file', 'apps/tvos/www/bench/bridge.js']);
  run('npx', ['rolldown', './apps/tvos/bench/canvasTest.ts', '--format', 'iife', '--minify', '--file', 'apps/tvos/www/bench/canvas-test.js']);
  if (game) {
    run('npx', ['vite', 'build', '--config', 'apps/tvos/vite.config.ts']);
    cpSync(path.join(appDir, 'dist'), path.join(www), { recursive: true });
  }
  await copyFonts();
  writeFileSync(path.join(www, 'config.json'), JSON.stringify(game
    ? { script: 'game.js', url: `http://aerodance.local/${ghost ? '?input=ghost' : ''}`, site, fit: 'fill', pixelated: true }
    : { script: 'bench/aero-bench.js', url: 'http://aerodance.local/bench/aero-bench.html', fit: 'contain' }));
  if (spawnSync('xcodegen', ['--version']).error) throw Error('XcodeGen is needed to generate the Xcode project: brew install xcodegen');
  const env = { ...process.env, TVOS_TEAM_ID: TEAM_ID, TVOS_BUNDLE_ID: BUNDLE_ID };
  run('xcodegen', ['generate', '--quiet'], appDir, env);
  if (!release) {
    // Development builds report to (and log to) the Mac over the local network.
    const plist = path.join(appDir, 'Info.plist');
    run('plutil', ['-insert', 'NSLocalNetworkUsageDescription', '-string', "Sends performance diagnostics to the developer's Mac during testing.", plist]);
    run('plutil', ['-insert', 'NSAppTransportSecurity', '-json', '{"NSAllowsLocalNetworking":true}', plist]);
  }
  run('xcodebuild', [
    '-project', 'AerodanceJSC.xcodeproj', '-scheme', 'AerodanceJSC', '-configuration', 'Release',
    '-destination', sim ? 'generic/platform=tvOS Simulator' : 'generic/platform=tvOS', '-derivedDataPath', 'build',
    ...(sim ? ['CODE_SIGNING_ALLOWED=NO', 'ARCHS=arm64'] : ['-allowProvisioningUpdates', '-allowProvisioningDeviceRegistration']), '-quiet', 'build',
  ], appDir, env);
  console.log(`Built ${appPath(sim)}`);
}

const appPath = (sim: boolean) => path.join(appDir, `build/Build/Products/Release-${sim ? 'appletvsimulator' : 'appletvos'}/aerodance.app`);

function launch(target: { sim?: string; device?: string }, config: string) {
  if (target.sim) {
    run('xcrun', ['simctl', 'install', target.sim, appPath(true)]);
    run('xcrun', ['simctl', 'launch', '--console-pty', '--terminate-running-process', target.sim, BUNDLE_ID, '--config', config]);
  } else {
    const device = target.device ?? '';
    run('xcrun', ['devicectl', 'device', 'install', 'app', '--device', device, '--quiet', appPath(false)]);
    run('xcrun', ['devicectl', 'device', 'process', 'launch', '--device', device, '--terminate-existing', '--console', BUNDLE_ID, '--config', config]);
  }
}

async function main() {
  const [cmd, ...args] = process.argv.slice(2);
  const flag = (name: string) => { const i = args.indexOf(name); return i < 0 ? undefined : args.splice(i, 2)[1] ?? ''; };
  const has = (name: string) => { const i = args.indexOf(name); if (i >= 0) args.splice(i, 1); return i >= 0; };
  if (!cmd || cmd === 'help' || cmd === '--help') return console.log(USAGE);
  if (cmd === 'build') { const site = flag('--site'); return build(has('--sim'), has('--game'), has('--release'), site, has('--ghost')); }
  if (cmd === 'run') {
    const sim = flag('--sim'), device = flag('--device'), config = flag('--config') ?? readFileSync(path.join(www, 'config.json'), 'utf8');
    if (!sim && !device) throw Error('run needs --sim <udid> or --device <udid>');
    return launch({ sim, device }, config);
  }
  throw Error(`Unknown command ${cmd}\n\n${USAGE}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
